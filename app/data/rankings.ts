// UFC 공식 Meta 랭킹과 기존 미디어 랭킹의 체급별 스냅샷을 제공한다.
export type RankingEntry = {
  rank: number;
  name: string;
};

export type RankingDivision = {
  id: string;
  label: string;
  englishLabel: string;
  champion: string;
  media: RankingEntry[];
  meta: RankingEntry[];
};

type RankingInput = string | readonly [rank: number, name: string];

const ranked = (...fighters: RankingInput[]): RankingEntry[] =>
  fighters.map((fighter, index) =>
    typeof fighter === "string"
      ? { rank: index + 1, name: fighter }
      : { rank: fighter[0], name: fighter[1] },
  );

